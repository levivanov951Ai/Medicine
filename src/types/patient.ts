/**
 * Пациент — владелец аккаунта (PD-01, PD-10: один пациент, без семейных профилей).
 *
 * Только то, что реально показывают экраны: имя и телефон.
 * Медицинских сведений здесь нет и быть не должно (PD-09):
 * ни диагнозов, ни медкарты, ни документов, ни результатов анализов.
 * Это НЕ модель будущей CRM — при интеграции поля сверяются с ней.
 */
export interface Patient {
  id: string;
  /**
   * Имя. `null` — пациент вошёл через /login и имя ещё не указал:
   * отдельной регистрации нет, профиль создаётся по одному телефону.
   * Имя спрашивается при первой записи или указывается в профиле.
   */
  name: string | null;
  /** 10 цифр после «+7». */
  phoneDigits: string;
  /** Когда профиль создан, ISO 8601. */
  createdAt: string;
}
